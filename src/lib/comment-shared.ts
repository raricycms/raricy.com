// ─────────────────────────────────────────────────────────────────────────────
// comment-shared.ts — 评论区「纯常量」，供服务端与客户端共享。
//
// 【为什么要单独拆一个文件】CommentSection 是客户端组件（'use client'），而
// comment-service.ts 依赖 prisma / auth.ts → next/headers 等 server-only 模块 ——
// 客户端若从它 import 哪怕只是一个常量，也会把整条服务端依赖链打进浏览器包
// （构建报错，或更糟：静默带上不该到前端的代码）。常量是纯数据、无运行时副作用，
// 放这里让两端共享。同款做法见 src/lib/chat-shared.ts。
// ─────────────────────────────────────────────────────────────────────────────

/** 纯文本评论上限。 */
export const COMMENT_TEXT_MAX = 2000;

/**
 * 带附件（图床图片 / 引用博客）评论的图注上限。
 *
 * 比纯文本档短得多，与聊天 CHAT_CAPTION_MAX 同口径：「图片 + 2000 字」一条评论
 * 在楼中楼里排版会很难看，而且带附件时正文本来就是个图注。
 *
 * ⚠️ 这里只是**前端先拦一道**（省一次白跑的请求 + 给出即时反馈）；真正的权威在
 * 服务端 createComment —— 前端校验永远只是体验，不是安全边界。
 */
export const COMMENT_CAPTION_MAX = 500;
