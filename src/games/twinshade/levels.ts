// ─────────────────────────────────────────────────────────────────────────────
// levels.ts — 双影的关卡表（作者手写；字符表与校验规则见 types.ts 的 LevelDef）
//
// ── 写关卡前必须知道的两条几何事实 ────────────────────────────────────────────
// ① 两个身体**永远保持相对位置**：它们每一步同方向、同位移，所以
//    `B − A` 在一整局里恒定（除了冰面让某一边多滑几格）。
//    推论：不用冰面的关卡，**两盏灯的相对位置必须与两侧出生点的相对位置
//    完全一致**，否则这一关根本无解。这条最容易写错 —— 而写错只是「无解」，
//    不会报格式错，所以 scripts/twinshade-levels.ts 会专门提示这条。
// ② 冰面是唯一能改变相对位置的东西，因此「错位」类关卡必须用冰面把距离拉开。
//    第三章的主题正是：先让两侧错开，再谈别的。
//
// ── 交付纪律 ────────────────────────────────────────────────────────────────
// 每改一关都跑一次 `npx tsx scripts/twinshade-levels.ts`（打印 par / 最优 /
// 推了几次石头 / 滑了几格的对账表）；par 必须是 **solver 算出来的最优步数**，
// 不许拍到「差不多」。`--path <id>` 打印最优走法，用来验证设计意图。
// 冰面关卡先跑 `--sim <方向串> <id>` 看两个身体最终停在哪，再把灯填到那两个坐标上
// —— 滑行距离靠心算必错。
// ─────────────────────────────────────────────────────────────────────────────

